export const LANGS = ['zh', 'en', 'ja', 'ko'];
const HTML_LANG = { zh: 'zh-CN', en: 'en', ja: 'ja', ko: 'ko' };

// 与 imgcrop 一致的路径映射：根路径 = 中文，/en /ja /ko（/zh 也接受）
export const langToPath = { zh: '/', en: '/en', ja: '/ja', ko: '/ko' };
export const pathToLang = { '/zh': 'zh', '/en': 'en', '/ja': 'ja', '/ko': 'ko' };

function normalizeLang(value) {
  return LANGS.includes(value) ? value : null;
}

function detectLang() {
  try {
    const saved = normalizeLang(localStorage.getItem('frame-extractor-lang'));
    if (saved) return saved;
    const nav = (typeof navigator !== 'undefined' && navigator.language) || '';
    if (/^zh\b/i.test(nav)) return 'zh';
    if (/^ja\b/i.test(nav)) return 'ja';
    if (/^ko\b/i.test(nav)) return 'ko';
    return 'en';
  } catch {
    return 'zh';
  }
}

export const i18n = reactive({
  lang: detectLang(),
  t(key, params) {
    let text =
      messages[this.lang]?.[key] ?? messages.en[key] ?? messages.zh[key] ?? key;
    if (params) {
      for (const [name, value] of Object.entries(params)) {
        text = text.replaceAll(`{${name}}`, String(value));
      }
    }
    return text;
  },
});

export function setLang(lang) {
  i18n.lang = normalizeLang(lang) || 'zh';
  try {
    localStorage.setItem('frame-extractor-lang', i18n.lang);
  } catch {
    /* 隐私模式下 localStorage 不可用 */
  }
  document.documentElement.lang = HTML_LANG[i18n.lang];
}
